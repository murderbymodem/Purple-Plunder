#!/usr/bin/env python3
"""
Regenerates THIRD-PARTY-NOTICES.md from the NuGet packages that end up in the Windows and Linux builds.

Run from the repository root after changing dependencies:

    dotnet restore PurplePlunder/PurplePlunder/PurplePlunder.csproj -r win-x64
    python3 scripts/generate-third-party-notices.py
"""
import glob
import html
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.join(ROOT, "PurplePlunder", "PurplePlunder", "PurplePlunder.csproj")
PACKAGES = os.environ.get("NUGET_PACKAGES") or os.path.join(os.path.expanduser("~"), ".nuget", "packages")

# Not part of the release build: build tooling, debug-only packages and natives for other platforms
EXCLUDE = re.compile(r"^(Avalonia\.BuildServices|Avalonia\.Diagnostics|Microsoft\.DotNet\.UpgradeAssistant.*)$"
                     r"|\.NativeAssets\.(macOS|WebAssembly)$")

# Packages whose nuspec only links to a license file
KNOWN_LICENSES = {
    "Ninject": "Apache-2.0 (dual-licensed Apache-2.0 / Ms-PL, used under Apache-2.0)",
    "Avalonia.Angle.Windows.Natives": "BSD-3-Clause (ANGLE)",
}

